  /**
   * Умная математическая диагностика ошибки ученика (Раздел 8 ТЗ):
   * Не просто «Неверно», а точное объяснение причины ошибки!
   */
  function diagnoseError(problem, enteredParts, enteredTotal) {
    const expectedTotal = problem.answer;
    const expectedParts = problem.partAreas;

    if (enteredTotal === expectedTotal) {
      return {
        ok: true,
        message: 'Великолепно! Площадь найдена абсолютно верно: ' + expectedTotal + ' см²!'
      };
    }

    // 1. Проверка: не забыл ли ученик разделить на 2 при вычислении площади треугольника
    if (problem.wrongNoDiv2 && enteredTotal === problem.wrongNoDiv2) {
      return {
        ok: false,
        message: 'Не забудь, что при нахождении площади треугольника нужно разделить произведение основания и высоты на 2!'
      };
    }

    // 2. Проверка: не посчитал ли ученик периметр вместо площади
    if (problem.perimeterTrap && enteredTotal === problem.perimeterTrap) {
      return {
        ok: false,
        message: 'Кажется, ты сложил стороны (нашёл периметр). Чтобы найти площадь прямоугольника, нужно длину умножить на ширину!'
      };
    }

    // 3. Проверка промежуточных площадей частей, если ученик их ввёл
    if (Array.isArray(enteredParts) && enteredParts.length === expectedParts.length && expectedParts.length > 1) {
      const allPartsValid = enteredParts.every((val, i) => val === expectedParts[i]);
      if (allPartsValid && enteredTotal !== expectedTotal) {
        return {
          ok: false,
          message: 'Ты правильно нашёл площади всех отдельных частей (' + expectedParts.join(' + ') + '), но проверь их сложение!'
        };
      }

      // Проверяем каждую часть по отдельности
      for (let i = 0; i < expectedParts.length; i++) {
        const userP = enteredParts[i];
        const expP = expectedParts[i];
        if (!Number.isNaN(userP) && userP !== expP) {
          const partObj = problem.figure.parts[i];
          if (partObj && partObj.type && partObj.type.startsWith('tri')) {
            if (userP === expP * 2) {
              return {
                ok: false,
                message: `В части S${i + 1} (треугольник) ты умножил основание на высоту (${userP}), но забыл разделить на 2!`
              };
            }
            return {
              ok: false,
              message: `Проверь вычисление площади треугольника S${i + 1}: умножь основание на высоту и раздели на 2.`
            };
          } else {
            return {
              ok: false,
              message: `Проверь, правильно ли ты вычислил площадь прямоугольника S${i + 1} (${partObj ? partObj.name : ''}).`
            };
          }
        }
      }
    }

    // 4. Общая подсказка по типу задачи
    if (expectedParts.length === 1) {
      const onlyPart = problem.figure.parts[0];
      if (onlyPart && onlyPart.type.startsWith('tri')) {
        return {
          ok: false,
          message: 'Проверь вычисление площади треугольника: используй формулу S = (a × h) : 2.'
        };
      }
      return {
        ok: false,
        message: 'Проверь, правильно ли ты вычислил площадь прямоугольника по формуле S = a × b.'
      };
    }

    return {
      ok: false,
      message: 'Ответ пока не совпал. Проверь площади отдельных частей и аккуратно сложи их. Нажми «Подсказка», если нужна помощь!'
    };
  }

  return {
    THINKING_TASKS,
    TRAINER_PROBLEMS,
    diagnoseError
  };
